#include <iostream>

using namespace std;

int main()
{
	int a = 5, b = 8;
	// r - ссылка на a
	int& r = a;
	// s - тоже ссылка на a
	int& s = a;
	// copy - новая переменная, в которую копируется значение a, после инициализации они уже независима
	int copy = a;

	// r - ссылка на a, так что теперь a = b (a = 8)
	r = b;
	// s - это тоже ссылка на a, так что a += 2 (a = 10, b = 8)
	s += 2;
	// копируем в b значение copy, теперь b = 5 (copy = 5)
	b = copy;


	// copy не меняется при изменении r или s, т.к copy - это независимая переменная, в которую мыпросто скопировали значение a.


	cout << "a = " << a << "\nb = " << b << "\nr = " << r << "\ns = " << s << "\ncopy = " << copy;


	return 0;
}