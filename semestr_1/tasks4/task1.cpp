#include <iostream>

int main()
{
	int a = 10;
	int b = 20;
	int& r = a;

	/*		r - это ссылка на переменную <a>, поэтому, когда мы изменяем <r>, мы по сути меняем значение <a>.
			r = b значит, что мы присваиваем <a> значение <b> (20), а затем r++ увеличивает значение <r> на 1, а значит меняется и <a> на 1. 	  */
	r = b;
	r++;
	std::cout << "a = " << a << "\n" << "b = " << b;

	return 0;
}