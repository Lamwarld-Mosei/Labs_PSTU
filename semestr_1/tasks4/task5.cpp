#include <iostream>

using namespace std;

int main()
{
	int a = 2, b = 5, c = 8;
	// p - указатель на a
	int* p = &a;
	// r - ссылка на a
	int& r = a;
	// copy - копия данных, которые лежат под указателем p (copy = a => copy = 2)
	int copy = *p;
	// присваиваем переменной под указателем p, данные из b (a = b => a = 5)
	*p = b;
	// теперь указатель указывает на адрес переменной c
	p = &c;
	// данные под ссылкой r переписываются данными из указателя p (r - по сути a, *p - это данные из c, a = c => a = 8)
	r = *p;
	// переменная под указателем p переписывается на b + copy (c = 5 + 2)
	*p = b + copy;
	// теперь указатель указывает на адрес переменной b
	p = &b;
	// переменной под указателем p (b) присваивается значение r - copy (r - ссылка на a, copy = 2, b = 8 - 2) 
	*p = r - copy;
	// r - ссылка на a, a++ - это a+1, a = 9
	r++;


	//Куда указывает p в конце? Что обозначает r?
	//p указывает на адрес переменной b; r - ссылка на a, по сути r - второе имя для переменной a.


	cout << "a = " << a << "\nb = " << b << "\nc = " << c << "\ncopy = " << copy;


	return 0;
}