#include <iostream>

using namespace std;

int main()
{
	int a = 4, b = 9;
	// p - указатель на переменную <a>
	int* p = &a;
	// q - указатель на переменную <a>, потому что мы копируем адрес из <p> в <q>, теперь это 2 несвязанных между собой указателя
	int* q = p;
	// r - это ссылка на переменную <a>, потому что выражение *p - это и есть сама переменная <a>, потому что <p> указывает на адрес <a>
	int& r = *p;
	// p - теперь указатель на переменную <b>, но остальные переменные от этого не изменяться, потому что <q> - это копия, а <r> - ссылка
	// конкретно на <a>
	p = &b;

	// изменяем то, что находится под <q>, то есть это <a> и прибавляем к нему значение под указателем <p>, то есть <a += 9>, теперь <a> = 13
	*q += *p;
	// изменяем то, что находится под <p>, то есть это <b>. <r> ссылка на <a>, то есть <b = a - 3>, теперь <b> = 10
	*p = r - 3;
	// изменяем <q>, теперь <q> указывает на то же, на что указывает <p>, то есть на <b>
	q = p;
	// изменяем то, что находится под указателем <q>, то есть это <b>. <r> всё ещё ссылка на <a>, то есть <b += a>, теперь <b> = 23
	*q += r;


	// p указывает на <b>, q указывает на <b>, r - ссылка на <a>

	
	cout << "a = " << a << "\nb = " << b << "\nr = " << r;

	return 0;
}